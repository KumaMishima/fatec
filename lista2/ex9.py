#9. Área do Círculo (Potência **)
#Peça o raio (número real) de um círculo. Calcule e exiba a área usando a fórmula:
#Área = 3.14 * raio²
#Uso obrigatorio do operador de potência **

raio = float(input('Digite o raio do circulo. '));
area = 3.14 * raio ** 2;

print(f"A area do circulo é de {area}");